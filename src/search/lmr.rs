/// Base reduction for the `i`-th move (i ≥ 3) at `depth` (≥ 3).
/// shortcut: depths past 127 reuse row 127, only reachable through very long check extensions.
pub fn reduction(depth: usize, i: usize) -> usize {
    LMR_THRESHOLDS[depth.min(127)].iter().take_while(|&&t| i >= t as usize).count()
}

#[cfg(test)]
mod tests {
    use super::reduction;

    // The table must match the formula it replaced; checked where it was generated (glibc's ln).
    #[cfg(all(target_arch = "x86_64", target_os = "linux"))]
    #[test]
    fn table_matches_formula() {
        for d in 3..128 {
            for i in 3..256 {
                let r = (0.75 + (d as f64).ln() * (i as f64).ln() / 2.25) as usize;
                assert_eq!(reduction(d, i), r, "depth {d} move {i}");
            }
        }
    }

    #[test]
    fn table_spot_values() {
        assert_eq!(reduction(3, 3), 1);
        assert_eq!(reduction(3, 13), 2);
        assert_eq!(reduction(64, 255), 10);
        assert_eq!(reduction(127, 255), 12);
    }
}
